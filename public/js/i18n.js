const urlLang = new URLSearchParams(location.search).get('lang');
let lang = urlLang === 'en' || urlLang === 'id' ? urlLang : 'id';

export function setLang(l) {
  if (urlLang === 'en' || urlLang === 'id') return false; // the URL wins
  const next = l === 'en' ? 'en' : 'id';
  if (next === lang) return false;
  lang = next;
  applyStatic();
  return true;
}

export const getLang = () => lang;

export function t(key, vars = {}) {
  let s = STRINGS[lang][key] ?? STRINGS.id[key] ?? key;
  for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function applyStatic(root = document) {
  document.documentElement.lang = lang;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
}

/** Escape text for innerHTML. */
export const esc = (s) => String(s ?? '').replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);

export const fmtNum = (n) => new Intl.NumberFormat(lang === 'en' ? 'en-US' : 'id-ID').format(n);

export function fmtTime(ms) {
  const s = Math.max(0, Math.ceil(ms / 1000));
  return `${Math.floor(s / 60)}:${String(s % 60).padStart(2, '0')}`;
}
